import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const write=(p,s)=>fs.writeFileSync(path.join(root,p),s);
const unescape=s=>s.replace(/\\([nrt\\"'])/g,(_,c)=>({n:'\n',r:'\r',t:'\t'}[c]??c));
const dictionary=JSON.parse(read('localization/en.json'));
const used=new Map();
const PART=150000;
function tables(rows,q){
  const head='-- Generated by tools/build-localization.mjs; edit localization/en.json.\n';const parts=[[]];let size=0;
  for(const r of rows){const line=`    {${q(r.source)},${q(r.en)}},`;const n=Buffer.byteLength(line)+1;if(size+n>PART&&parts.at(-1).length){parts.push([]);size=0}parts.at(-1).push(line);size+=n}
  const out={};parts.forEach((p,i)=>{out[`src/core/LocalizationData_${i+1}.luau`]=head+'return {\n'+p.join('\n')+'\n}\n'});
  const req=i=>`if script then require(script.Parent.LocalizationData_${i})else require('./LocalizationData_${i}')`;
  out['src/core/LocalizationData.luau']=head+'local out={}\n'+parts.map((_,i)=>`for _,row in ipairs(${req(i+1)})do table.insert(out,row)end`).join('\n')+'\nreturn out\n';
  return out;
}
const stale=want=>{
  const have=fs.readdirSync(path.join(root,'src/core')).filter(f=>/^LocalizationData(_\d+)?\.luau$/.test(f)).map(f=>'src/core/'+f).sort();
  return have.join()!==Object.keys(want).sort().join()||Object.entries(want).some(([p,s])=>read(p)!==s);
};
for(const dir of ['client','core','runtime','server'])for(const file of fs.readdirSync(path.join(root,'src',dir))){
  if(!file.endsWith('.luau')||/^(Localization|Combat|NativeClient|NativeServer|NationNamesKoData)/.test(file))continue;
  if(/^--\s*@dev-only/.test(read(`src/${dir}/${file}`)))continue;
  const code=read(`src/${dir}/${file}`).replace(/^\s*--.*$/gm,'');
  for(const m of code.matchAll(/"((?:\\.|[^"\\\r\n])*)"|'((?:\\.|[^'\\\r\n])*)'/g)){
    const s=m[1]??m[2];if(/[가-힣]/.test(s))used.set(s,`src/${dir}/${file}`);
  }
}
const maps=read('src/maps/Catalog.luau');
for(const m of maps.matchAll(/\["label"\]="([^"]+)",\["category"\]="([^"]+)",\["description"\]="([^"]+)",\["englishName"\]="([^"]+)"/g)){
  dictionary[m[1]]=m[4];for(const s of m.slice(1,4))used.set(s,'src/maps/Catalog.luau');
}
const missing=[...used].filter(([s])=>dictionary[s]===undefined).map(([source,file])=>({source,file}));
if(process.argv.includes('--check')){
  if(missing.length){console.log(JSON.stringify(missing,null,2));console.log(`LOCALIZATION MISSING ${missing.length}`);process.exit(1)}
  const rowsNow=[...used.keys()].sort().map(s=>({source:unescape(s),en:unescape(dictionary[s])}));
  const qq=s=>JSON.stringify(s).replace(/\\u([a-f\d]{4})/gi,(_,h)=>String.fromCharCode(parseInt(h,16)));
  if(stale(tables(rowsNow,qq))){console.log('LOCALIZATION STALE: run node tools/build-localization.mjs');process.exit(1)}
  console.log('LOCALIZATION OK '+rowsNow.length);process.exit(0);
}
write('evidence/localization-missing.json',JSON.stringify(missing,null,2));
if(missing.length){console.log(JSON.stringify(missing,null,2));throw Error(`${missing.length} missing English translations`);}
const rows=[...used.keys()].sort().map(s=>({source:unescape(s),en:unescape(dictionary[s])}));
const q=s=>JSON.stringify(s).replace(/\\u([a-f\d]{4})/gi,(_,h)=>String.fromCharCode(parseInt(h,16)));
for(const f of fs.readdirSync(path.join(root,'src/core')))if(/^LocalizationData_\d+\.luau$/.test(f))fs.rmSync(path.join(root,'src/core',f));
for(const [p,s] of Object.entries(tables(rows,q)))write(p,s);
const cell=s=>'"'+s.replaceAll('"','""')+'"';
const template=s=>{let n=0;return s.replace(/%%|%[-+ #0]*\d*(?:\.\d+)?[sdfiug]/g,t=>t==='%%'?'%':`{${++n}}`);};
const csvRows=rows.filter(r=>r.en!=='').map(r=>['toyfront_'+createHash('sha256').update(r.source).digest('hex').slice(0,16),'','',template(r.en),template(r.source)].map(cell).join(','));
const header='Key,Context,Example,Source,ko\r\n';
write('localization/Roblox.csv',header+csvRows.join('\r\n')+'\r\n');
fs.mkdirSync(path.join(root,'localization/batches'),{recursive:true});
for(let i=0;i<csvRows.length;i+=25)write('localization/batches/'+(i/25+1)+'.csv',header+csvRows.slice(i,i+25).join('\r\n')+'\r\n');
write('evidence/localization-coverage.json',JSON.stringify({sourceLocale:'en',codeLocale:'ko',englishEntries:rows.length,missing:0,ownLocales:['en','ko'],cloudLocales:['ja','es','pt','fr','de','id','th','vi','tr','ru','it','pl','ar','hi','zh-hans','zh-hant'],cloudStatus:'configure and verify in Creator Hub'},null,2));
console.log(`Localization: ${rows.length} Korean/English entries; CSV ready.`);
