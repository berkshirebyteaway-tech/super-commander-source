import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const table=JSON.parse(read('localization/nations.ko.json'));
const used=new Set();
for(const f of fs.readdirSync(path.join(root,'src/maps')).filter(f=>/^CatalogNations_\d+\.luau$/.test(f)))
  for(const m of read(`src/maps/${f}`).matchAll(/\["name"\]="([^"]*)"/g))if(/[A-Za-z]/.test(m[1]))used.add(m[1]);
const missing=[...used].filter(n=>!table[n]);
fs.writeFileSync(path.join(root,'evidence/nation-names-ko-missing.json'),JSON.stringify(missing,null,2));
if(missing.length)throw Error(`${missing.length} map country names have no Korean name (evidence/nation-names-ko-missing.json)`);
const q=s=>JSON.stringify(s).replace(/\\u([a-f\d]{4})/gi,(_,h)=>String.fromCharCode(parseInt(h,16)));
const rows=Object.keys(table).sort().filter(k=>table[k]&&table[k]!==k).map(k=>`[${q(k)}]=${q(table[k])}`);
const head='-- Generated by tools/build-nation-names-ko.mjs; edit localization/nations.ko.json.\n';
const parts=[];for(let i=0;i<rows.length;i+=1500)parts.push(rows.slice(i,i+1500));
for(const f of fs.readdirSync(path.join(root,'src/core')).filter(f=>/^NationNamesKoData_\d+\.luau$/.test(f)))fs.unlinkSync(path.join(root,'src/core',f));
parts.forEach((p,i)=>fs.writeFileSync(path.join(root,`src/core/NationNamesKoData_${i+1}.luau`),head+'return {\n'+p.join(',\n')+'\n}\n'));
const load=i=>`for k,v in pairs(if script then require(script.Parent.NationNamesKoData_${i})else require('./NationNamesKoData_${i}'))do out[k]=v end`;
fs.writeFileSync(path.join(root,'src/core/NationNamesKoData.luau'),head+'local out={}\n'+parts.map((_,i)=>load(i+1)).join('\n')+'\nreturn out\n');
console.log(`Nation names ko: ${rows.length} entries in ${parts.length} parts, ${used.size} map names, missing 0.`);
